#include<stdio.h>

int main()
{
    // Variable declaration
    int age = 20;
    char grade = 'A';
    float marks = 89.5;

    // Constant declaration
    const float PI = 3.14;

    // Display values
    printf("Age = %d\n", age);
    printf("Grade = %c\n", grade);
    printf("Marks = %.2f\n", marks);
    printf("Value of PI = %.2f\n", PI);

}
